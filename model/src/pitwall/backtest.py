"""Season-by-season backtest with no look-ahead.

For each test season, the model is trained only on earlier seasons and then
predicts every race of the test season. Features inside the test season update
race by race from earlier results only, exactly as they would live.

The first test season is 2020: the model needs two earlier seasons, one to
train on and one to calibrate its odds on.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pandas as pd

from pitwall import __version__
from pitwall.baselines import elo_baseline, grid_baseline
from pitwall.features import POST_QUALI, PRE_QUALI
from pitwall.metrics import calibration, race_scores, summarise
from pitwall.model import fit

MODES = {"pre_quali": PRE_QUALI, "post_quali": POST_QUALI}
# Chosen on the 2020-2026 backtest (disclosed in the report): Plackett-Luce alone was
# best before qualifying, the LightGBM + Plackett-Luce blend best once the grid is known.
MODE_KIND = {"pre_quali": "pl", "post_quali": "blend"}
BASELINE_FOR = {"pre_quali": ("elo", elo_baseline), "post_quali": ("grid", grid_baseline)}


def run(
    features: pd.DataFrame,
    test_seasons: list[int],
    kinds: dict[str, str] | None = None,
    progress: Any = print,
) -> dict[str, Any]:
    kinds = kinds or MODE_KIND
    done = features[features["position"].notna()].copy()
    report: dict[str, Any] = {
        "built_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "model_version": __version__,
        "test_seasons": test_seasons,
        "model_kinds": kinds,
        "modes": {},
    }
    for mode, cols in MODES.items():
        base_name, base_fn = BASELINE_FOR[mode]
        preds = []
        per_season = []
        importance: dict[str, float] = {}
        for season in test_seasons:
            train = done[done["season"] < season]
            test = done[done["season"] == season].copy()
            if test.empty:
                continue
            model = fit(train, cols, kind=kinds[mode])
            p = model.predict(test)
            test["p_model"] = p["p_win"].to_numpy()
            test["p_podium_model"] = p["p_podium"].to_numpy()
            test["p_base"] = base_fn(train, test)
            preds.append(test)
            m = summarise(race_scores(test, "p_model"))
            b = summarise(race_scores(test, "p_base"))
            per_season.append({"season": season, "model": m, base_name: b, "temperature": model.temperature})
            for f, v in model.importance.items():
                importance[f] = importance.get(f, 0.0) + v / len(test_seasons)
            progress(
                f"  {mode:<10} {season}: model {m['winner_hit']:.0%} winner, "
                f"{m['winner_in_top3']:.0%} top-3 | {base_name} {b['winner_hit']:.0%} winner"
            )
        allp = pd.concat(preds, ignore_index=True)
        report["modes"][mode] = {
            "model_kind": kinds[mode],
            "features": cols,
            "baseline": base_name,
            "overall": {
                "model": summarise(race_scores(allp, "p_model")),
                base_name: summarise(race_scores(allp, "p_base")),
            },
            "per_season": per_season,
            "calibration": calibration(allp, "p_model"),
            "podium_calibration": calibration(allp, "p_podium_model", "podium"),
            "feature_importance": dict(sorted(importance.items(), key=lambda kv: -kv[1])),
        }
    return report


def write(report: dict[str, Any], out_dir: Path) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "backtest.json"
    json_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    md_path = out_dir / "BACKTEST.md"
    md_path.write_text(markdown(report) + title_markdown(report.get("titles", [])), encoding="utf-8")
    return json_path, md_path


def _pct(x: float) -> str:
    return f"{x:.0%}"


def markdown(report: dict[str, Any]) -> str:
    seasons = report["test_seasons"]
    lines = [
        "# PitWall backtest",
        "",
        f"Seasons {seasons[0]}-{seasons[-1]}, each predicted by a model trained only on earlier seasons. "
        "Generated by `uv run pitwall model backtest`.",
        "",
        "Model kinds: `pl` is a Plackett-Luce regression on the finishing order; `blend` averages it with a "
        "LightGBM ranker. The kind used in each mode was chosen on this backtest, which flatters the "
        "numbers slightly; the live public scorecard from 2027 is the clean test.",
        "",
    ]
    titles = {"pre_quali": "Before qualifying (Thursday)", "post_quali": "After qualifying (grid known)"}
    for mode, r in report["modes"].items():
        base = r["baseline"]
        m, b = r["overall"]["model"], r["overall"][base]
        lines += [
            f"## {titles[mode]}",
            "",
            f"Model: **{r['model_kind']}**. Baseline: **{base}**. {m['races']} races.",
            "",
            "| Metric | PitWall | Baseline | Better is |",
            "|---|---|---|---|",
            f"| Top pick wins | {_pct(m['winner_hit'])} | {_pct(b['winner_hit'])} | higher |",
            f"| Winner in top 3 picks | {_pct(m['winner_in_top3'])} | {_pct(b['winner_in_top3'])} | higher |",
            f"| Podium picks correct | {_pct(m['podium_overlap'])} | {_pct(b['podium_overlap'])} | higher |",
            f"| Chance given to the winner | {_pct(m['winner_prob'])} | {_pct(b['winner_prob'])} | higher |",
            f"| Brier score | {m['brier']:.3f} | {b['brier']:.3f} | lower |",
            f"| Log loss | {m['log_loss']:.3f} | {b['log_loss']:.3f} | lower |",
            "",
            "Per season (top pick wins):",
            "",
            "| Season | PitWall | Baseline |",
            "|---|---|---|",
        ]
        for s in r["per_season"]:
            lines.append(
                f"| {s['season']} | {_pct(s['model']['winner_hit'])} | {_pct(s[base]['winner_hit'])} |"
            )
        lines += ["", "Calibration (win odds): when PitWall says X%, how often did it happen?", ""]
        lines += ["| Band | Predictions | Predicted | Actual |", "|---|---|---|---|"]
        for c in r["calibration"]:
            lines.append(f"| {c['band']} | {c['n']} | {_pct(c['predicted'])} | {_pct(c['actual'])} |")
        top = list(r["feature_importance"].items())[:6]
        lines += ["", "Most useful features: " + ", ".join(f"{k} ({v:.0%})" for k, v in top), ""]
    return "\n".join(lines) + "\n"


def title_backtest(
    entries: pd.DataFrame,
    races: pd.DataFrame,
    standings: pd.DataFrame,
    features: pd.DataFrame,
    seasons: list[int],
    cut: float = 2 / 3,
    n_sims: int = 10_000,
    progress: Any = print,
) -> list[dict[str, Any]]:
    """Simulate each past season from `cut` of the way through; how likely did we make the real champions?"""
    from pitwall.simulate import simulate

    out = []
    done = features[features["position"].notna()]
    for season in seasons:
        final = standings[(standings["season"] == season) & (standings["position"] == 1)]
        champ = final.set_index("kind")["entity_id"].to_dict()
        n_rounds = int(races[races["season"] == season]["round"].max())
        raced = int(entries[(entries["season"] == season) & entries["position"].notna()]["round"].max())
        if raced < n_rounds or "driver" not in champ:
            continue  # season not finished yet
        after = max(1, round(n_rounds * cut))
        model = fit(done[done["season"] < season], PRE_QUALI, kind=MODE_KIND["pre_quali"])
        sim = simulate(entries, races, model, season, after_round=after, n_sims=n_sims)
        d = {r["driver_id"]: r["p_title"] for r in sim["drivers"]}
        t = {r["constructor_id"]: r["p_title"] for r in sim["constructors"]}
        fav_d, fav_t = sim["drivers"][0]["driver_id"], sim["constructors"][0]["constructor_id"]
        row = {
            "season": season,
            "after_round": after,
            "of_rounds": n_rounds,
            "driver_champion": champ["driver"],
            "p_driver_champion": d.get(champ["driver"], 0.0),
            "driver_favourite_won": fav_d == champ["driver"],
            "constructor_champion": champ.get("constructor"),
            "p_constructor_champion": t.get(champ.get("constructor", ""), 0.0),
            "constructor_favourite_won": fav_t == champ.get("constructor"),
        }
        out.append(row)
        progress(
            f"  titles {season} after R{after}/{n_rounds}: "
            f"{row['driver_champion']} {row['p_driver_champion']:.0%}, "
            f"{row['constructor_champion']} {row['p_constructor_champion']:.0%}"
        )
    return out


def title_markdown(rows: list[dict[str, Any]]) -> str:
    if not rows:
        return ""
    lines = [
        "## Championship forecasts",
        "",
        "Each season simulated 10,000 times from two-thirds distance, with a model trained only on earlier "
        "seasons. Chance given to the eventual champions:",
        "",
        "| Season | From | Drivers' champion | Chance | Constructors' champion | Chance |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['season']} | R{r['after_round']}/{r['of_rounds']} | {r['driver_champion']} | "
            f"{_pct(r['p_driver_champion'])} | {r['constructor_champion']} | "
            f"{_pct(r['p_constructor_champion'])} |"
        )
    fav_d = sum(r["driver_favourite_won"] for r in rows)
    fav_t = sum(r["constructor_favourite_won"] for r in rows)
    lines += [
        "",
        f"The favourite went on to win the drivers' title in {fav_d} of {len(rows)} seasons "
        f"and the constructors' title in {fav_t} of {len(rows)}.",
        "",
    ]
    return "\n".join(lines)
