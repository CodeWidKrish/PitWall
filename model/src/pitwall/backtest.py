"""Season-by-season backtest with no look-ahead.

For each test season, the model is trained only on earlier seasons and then
predicts every race of the test season. Features inside the test season update
race by race from earlier results only, exactly as they would live.

The first test season is 2020: the model needs two earlier seasons, one to
train on and one to calibrate its odds on.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pandas as pd

from pitwall import __version__
from pitwall.baselines import elo_baseline, grid_baseline
from pitwall.features import POST_QUALI, PRE_QUALI
from pitwall.metrics import calibration, classification, confidence_bands, race_scores, summarise
from pitwall.model import fit, select_kind
from pitwall.simulate import IN_SEASON_SCALE, PRESEASON_SCALE

MODES = {"pre_quali": PRE_QUALI, "post_quali": POST_QUALI}
# Default kinds for quick use. The backtest itself does not use these: it selects the
# kind for every test season from earlier seasons only (see model.select_kind).
MODE_KIND = {"pre_quali": "pl", "post_quali": "blend"}
BASELINE_FOR = {"pre_quali": ("elo", elo_baseline), "post_quali": ("grid", grid_baseline)}


def run(
    features: pd.DataFrame,
    test_seasons: list[int],
    kinds: dict[str, str] | None = None,
    progress: Any = print,
) -> dict[str, Any]:
    done = features[features["position"].notna()].copy()
    report: dict[str, Any] = {
        "built_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "model_version": __version__,
        "test_seasons": test_seasons,
        "model_selection": (
            "walk-forward: for each test season, the kind with the lowest winner log loss "
            "on the two previous seasons"
        ),
        "modes": {},
    }
    for mode, cols in MODES.items():
        base_name, base_fn = BASELINE_FOR[mode]
        preds = []
        per_season = []
        importance: dict[str, float] = {}
        for season in test_seasons:
            train = done[done["season"] < season]
            test = done[done["season"] == season].copy()
            if test.empty:
                continue
            kind, val_losses = (kinds[mode], {}) if kinds else select_kind(train, cols)
            model = fit(train, cols, kind=kind)
            p = model.predict(test)
            test["p_model"] = p["p_win"].to_numpy()
            test["p_podium_model"] = p["p_podium"].to_numpy()
            test["p_base"] = base_fn(train, test)
            preds.append(test)
            m = summarise(race_scores(test, "p_model"))
            b = summarise(race_scores(test, "p_base"))
            per_season.append(
                {"season": season, "kind": kind, "validation_log_loss": val_losses, "model": m, base_name: b}
            )
            for f, v in model.importance.items():
                importance[f] = importance.get(f, 0.0) + v / len(test_seasons)
            progress(
                f"  {mode:<10} {season}: model {m['winner_hit']:.0%} winner, "
                f"{m['winner_in_top3']:.0%} top-3 | {base_name} {b['winner_hit']:.0%} winner"
            )
        allp = pd.concat(preds, ignore_index=True)
        report["modes"][mode] = {
            "kinds_used": {str(s["season"]): s["kind"] for s in per_season},
            "features": cols,
            "baseline": base_name,
            "overall": {
                "model": summarise(race_scores(allp, "p_model")),
                base_name: summarise(race_scores(allp, "p_base")),
            },
            "per_season": per_season,
            "classification": classification(allp, "p_model", "p_podium_model"),
            "confidence": confidence_bands(race_scores(allp, "p_model")),
            "calibration": calibration(allp, "p_model"),
            "podium_calibration": calibration(allp, "p_podium_model", "podium"),
            "feature_importance": dict(sorted(importance.items(), key=lambda kv: -kv[1])),
        }
    return report


def write(report: dict[str, Any], out_dir: Path) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "backtest.json"
    json_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    md_path = out_dir / "BACKTEST.md"
    md_path.write_text(
        markdown(report) + title_calibration_markdown(report.get("title_calibration", {})), encoding="utf-8"
    )
    return json_path, md_path


def _pct(x: float) -> str:
    return f"{x:.0%}"


def markdown(report: dict[str, Any]) -> str:
    seasons = report["test_seasons"]
    lines = [
        "# PitWall backtest",
        "",
        f"Seasons {seasons[0]}-{seasons[-1]}, each predicted by a model trained only on earlier seasons. "
        "Generated by `uv run pitwall model backtest`.",
        "",
        "Model kinds: `pl` is a Plackett-Luce regression on the finishing order, `lgbm` a LightGBM ranker, "
        "`blend` an average of the two. For every test season the kind is chosen by walk-forward validation "
        "on the two previous seasons only, so no choice is made with knowledge of the season being tested.",
        "",
    ]
    titles = {"pre_quali": "Before qualifying (Thursday)", "post_quali": "After qualifying (grid known)"}
    for mode, r in report["modes"].items():
        base = r["baseline"]
        m, b = r["overall"]["model"], r["overall"][base]
        lines += [
            f"## {titles[mode]}",
            "",
            f"Model kind per season (chosen from earlier seasons only): "
            f"{', '.join(f'{k} {v}' for k, v in r['kinds_used'].items())}. Baseline: **{base}**. "
            f"{m['races']} races.",
            "",
            "| Metric | PitWall | Baseline | Better is |",
            "|---|---|---|---|",
            f"| Top pick wins | {_pct(m['winner_hit'])} | {_pct(b['winner_hit'])} | higher |",
            f"| Winner in top 3 picks | {_pct(m['winner_in_top3'])} | {_pct(b['winner_in_top3'])} | higher |",
            f"| Podium picks correct | {_pct(m['podium_overlap'])} | {_pct(b['podium_overlap'])} | higher |",
            f"| Chance given to the winner | {_pct(m['winner_prob'])} | {_pct(b['winner_prob'])} | higher |",
            f"| Brier score | {m['brier']:.3f} | {b['brier']:.3f} | lower |",
            f"| Log loss | {m['log_loss']:.3f} | {b['log_loss']:.3f} | lower |",
            "",
            "Per season. Average favourite odds show how predictable PitWall judged each season to be:",
            "",
            "| Season | Kind | Top pick wins | Baseline | Average favourite odds |",
            "|---|---|---|---|---|",
        ]
        for s in r["per_season"]:
            lines.append(
                f"| {s['season']} | {s['kind']} | {_pct(s['model']['winner_hit'])} | "
                f"{_pct(s[base]['winner_hit'])} | {_pct(s['model']['favourite_prob'])} |"
            )
        lines += [
            "",
            "Does PitWall know when a race is open? Races grouped by its confidence in the favourite:",
            "",
            "| Favourite's odds | Races | Average odds | Favourite won | Winner in top 3 |",
            "|---|---|---|---|---|",
        ]
        for c in r["confidence"]:
            lines.append(
                f"| {c['band']} | {c['races']} | {_pct(c['favourite_prob'])} | "
                f"{_pct(c['favourite_won'])} | {_pct(c['winner_in_top3'])} |"
            )
        cl = r["classification"]
        lines += [
            "",
            "Classification view. Each race, the top pick is predicted to win and the top three to make "
            "the podium; every driver-race counts once.",
            "",
            "| | Win | Podium |",
            "|---|---|---|",
            f"| True positives | {cl['win']['tp']} | {cl['podium']['tp']} |",
            f"| False positives | {cl['win']['fp']} | {cl['podium']['fp']} |",
            f"| False negatives | {cl['win']['fn']} | {cl['podium']['fn']} |",
            f"| True negatives | {cl['win']['tn']} | {cl['podium']['tn']} |",
            f"| Accuracy | {_pct(cl['win']['accuracy'])} | {_pct(cl['podium']['accuracy'])} |",
            f"| Error rate | {_pct(cl['win']['error_rate'])} | {_pct(cl['podium']['error_rate'])} |",
            f"| Precision | {_pct(cl['win']['precision'])} | {_pct(cl['podium']['precision'])} |",
            f"| Recall | {_pct(cl['win']['recall'])} | {_pct(cl['podium']['recall'])} |",
            f"| F1 | {_pct(cl['win']['f1'])} | {_pct(cl['podium']['f1'])} |",
            f"| ROC AUC | {_pct(cl['win']['roc_auc'])} | {_pct(cl['podium']['roc_auc'])} |",
            f"| Calibration error | {cl['win']['calibration_error']:.1%} | "
            f"{cl['podium']['calibration_error']:.1%} |",
            f"| Accuracy of always saying no | {_pct(cl['win']['always_no_accuracy'])} | "
            f"{_pct(cl['podium']['always_no_accuracy'])} |",
            "",
            "Accuracy is inflated by imbalance (most drivers don't win, so always saying no scores highly). "
            "Precision, recall, ROC AUC and calibration error are the meaningful numbers.",
        ]
        lines += ["", "Calibration (win odds): when PitWall says X%, how often did it happen?", ""]
        lines += ["| Band | Predictions | Predicted | Actual |", "|---|---|---|---|"]
        for c in r["calibration"]:
            lines.append(f"| {c['band']} | {c['n']} | {_pct(c['predicted'])} | {_pct(c['actual'])} |")
        top = list(r["feature_importance"].items())[:6]
        lines += ["", "Most useful features: " + ", ".join(f"{k} ({v:.0%})" for k, v in top), ""]
    return "\n".join(lines) + "\n"


TITLE_CUTS = (0.0, 0.25, 0.5, 2 / 3, 0.8)
SWING_SCALES = (0.0, 0.5, 1.0, 1.5, 2.0, 3.0)  # multiples of (team 0.6, driver 0.3)


def title_calibration(
    entries: pd.DataFrame,
    races: pd.DataFrame,
    standings: pd.DataFrame,
    features: pd.DataFrame,
    seasons: list[int],
    n_sims: int = 3000,
    progress: Any = print,
) -> dict[str, Any]:
    """Simulate each finished season from several points (pre-season to 80%) and tune the form swing.

    For every (season, cut) the model is trained only on earlier seasons. Each swing size
    is scored by the log loss of the eventual champions; pre-season and in-season are
    tuned separately because winter changes are bigger than mid-season ones.
    """
    import numpy as np

    from pitwall.features import PRE_QUALI as cols
    from pitwall.simulate import current_state, future_features, simulate

    done = features[features["position"].notna()]
    rows: list[dict[str, Any]] = []
    for season in seasons:
        final = standings[(standings["season"] == season) & (standings["position"] == 1)]
        champ = final.set_index("kind")["entity_id"].to_dict()
        n_rounds = int(races[races["season"] == season]["round"].max())
        raced = int(entries[(entries["season"] == season) & entries["position"].notna()]["round"].max())
        if raced < n_rounds or "driver" not in champ:
            continue
        train = done[done["season"] < season]
        kind, _ = select_kind(train, cols)
        model = fit(train, cols, kind=kind)
        for cut in TITLE_CUTS:
            after = round(n_rounds * cut)
            state = current_state(entries, races, season, after_round=after)
            feats = future_features(entries, races, state)
            for scale in SWING_SCALES:
                sim = simulate(
                    entries,
                    races,
                    model,
                    season,
                    after_round=after,
                    n_sims=n_sims,
                    team_form_sigma=0.6 * scale,
                    driver_form_sigma=0.3 * scale,
                    state=state,
                    feats=feats,
                )
                d = {r["driver_id"]: r["p_title"] for r in sim["drivers"]}
                t = {r["constructor_id"]: r["p_title"] for r in sim["constructors"]}
                rows.append(
                    {
                        "season": season,
                        "after_round": after,
                        "of_rounds": n_rounds,
                        "preseason": after == 0,
                        "scale": scale,
                        "driver_champion": champ["driver"],
                        "p_driver": d.get(champ["driver"], 0.0),
                        "driver_fav_won": sim["drivers"][0]["driver_id"] == champ["driver"],
                        "constructor_champion": champ.get("constructor"),
                        "p_constructor": t.get(champ.get("constructor", ""), 0.0),
                        "constructor_fav_won": sim["constructors"][0]["constructor_id"]
                        == champ.get("constructor"),
                    }
                )
        progress(f"  titles {season}: simulated from {len(TITLE_CUTS)} points ({kind})")

    df = pd.DataFrame(rows)

    def score(g: pd.DataFrame) -> float:
        p = np.clip(np.concatenate([g["p_driver"].to_numpy(), g["p_constructor"].to_numpy()]), 1e-3, 1)
        return float(-np.mean(np.log(p)))

    tuned: dict[str, Any] = {}
    for phase, mask in (("preseason", df["preseason"]), ("in_season", ~df["preseason"])):
        losses = {float(s): round(score(df[mask & (df["scale"] == s)]), 4) for s in SWING_SCALES}
        best = min(losses, key=lambda s: losses[s])
        tuned[phase] = {"log_loss_by_scale": losses, "best_scale": best}
    return {"cuts": list(TITLE_CUTS), "rows": df.to_dict("records"), "tuned": tuned}


def title_calibration_markdown(cal: dict[str, Any]) -> str:
    if not cal or not cal.get("rows"):
        return ""
    df = pd.DataFrame(cal["rows"])
    lines = [
        "## Championship forecasts",
        "",
        "Each finished season simulated from five points (pre-season, 25%, 50%, 67% and 80% distance) with a "
        "model trained only on earlier seasons. The size of the season-long form swing is tuned on these "
        "forecasts: pre-season and in-season separately.",
        "",
        "| Swing scale | Pre-season log loss | In-season log loss |",
        "|---|---|---|",
    ]
    pre, ins = cal["tuned"]["preseason"], cal["tuned"]["in_season"]
    for s in pre["log_loss_by_scale"]:
        lines.append(f"| {s}x | {pre['log_loss_by_scale'][s]} | {ins['log_loss_by_scale'][s]} |")
    lines += [
        "",
        f"Lowest log loss: {pre['best_scale']}x before the season, {ins['best_scale']}x during it "
        "(1x = team 0.6, driver 0.3 in log-odds).",
        "",
        f"In use: {PRESEASON_SCALE}x before the season, {IN_SEASON_SCALE}x during it. "
        + (
            "The pre-season value is overruled: it rests on six forecasts, and with no swing the "
            "model gave an eventual champion 0% (McLaren, 2024). Winter changes are at least as "
            "uncertain as in-season ones, so pre-season uses the in-season value."
            if pre["best_scale"] != PRESEASON_SCALE
            else ""
        ),
        "",
        "Chance given to the eventual champions with the lowest-loss swing:",
        "",
        "| Season | From | Drivers' champion | Chance | Constructors' champion | Chance |",
        "|---|---|---|---|---|---|",
    ]
    chosen = df[
        (df["preseason"] & (df["scale"] == pre["best_scale"]))
        | (~df["preseason"] & (df["scale"] == ins["best_scale"]))
    ]
    for r in chosen.sort_values(["season", "after_round"]).to_dict("records"):
        start = "pre-season" if r["preseason"] else f"R{r['after_round']}/{r['of_rounds']}"
        lines.append(
            f"| {r['season']} | {start} | {r['driver_champion']} | {_pct(r['p_driver'])} | "
            f"{r['constructor_champion']} | {_pct(r['p_constructor'])} |"
        )
    n = len(chosen)
    lines += [
        "",
        f"The favourite went on to win the drivers' title in {int(chosen['driver_fav_won'].sum())} of {n} "
        f"forecasts and the constructors' title in {int(chosen['constructor_fav_won'].sum())} of {n}.",
        "",
    ]
    return "\n".join(lines)
